def _type_name(annotation: Any) -> str:
    origin = get_origin(annotation)
    if origin is None:
        if hasattr(annotation, "__name__"):
            return annotation.__name__
        return str(annotation).replace("typing.", "")
    args = ", ".join(_type_name(arg) for arg in get_args(annotation) or ())
    origin_name = getattr(origin, "__name__", str(origin))
    if args:
        return f"{origin_name}[{args}]"
    return origin_name


def _default_repr(value: Any) -> str:
    if value is ...:
        return "*(required)*"
    try:
        from pydantic import BaseModel
        from pydantic_core import PydanticUndefined

        if value is PydanticUndefined:
            return "*(required)*"
        if isinstance(value, BaseModel):
            return "`{}` (nested defaults)"
    except Exception:
        pass
    text = json.dumps(value, default=str)
    if len(text) > 80:
        return "`" + text[:77] + "...`"
    return f"`{text}`"


def _walk_model(model: type, prefix: str = "") -> list[tuple[str, Any]]:
    from pydantic import BaseModel

    rows: list[tuple[str, Any]] = []
    for name, field in model.model_fields.items():
        key = f"{prefix}.{name}" if prefix else name
        annotation = field.annotation
        origin = get_origin(annotation)
        args = get_args(annotation)
        nested = None
        if isinstance(annotation, type) and issubclass(annotation, BaseModel) and annotation is not model:
            nested = annotation
        elif origin is None:
            nested = None
        else:
            for arg in args:
                if isinstance(arg, type) and issubclass(arg, BaseModel):
                    nested = arg
                    break
        rows.append((key, field))
        if nested is not None and name != "rules":
            rows.extend(_walk_model(nested, key))
    return rows


def _field_default(field: Any) -> str:
    factory = getattr(field, "default_factory", None)
    if factory is not None:
        try:
            return _default_repr(factory())
        except TypeError:
            return "`{}` (nested defaults)"
    return _default_repr(field.default)


def _restart_for(key: str) -> str:
    if key in RESTART:
        return RESTART[key]
    parts = key.split(".")
    for i in range(len(parts) - 1, 0, -1):
        parent = ".".join(parts[:i])
        if parent in RESTART:
            return RESTART[parent]
    return "orchestrator restart unless listed as hot-reload above"


