def write_openapi(path: Path) -> None:
    import importlib.util

    module_path = ROOT / "scripts" / "generate-openapi.py"
    spec = importlib.util.spec_from_file_location("generate_openapi", module_path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {module_path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    yaml_path, json_path = module.write_openapi_files(path.parent)
    print(f"wrote {yaml_path.relative_to(ROOT)}")
    print(f"wrote {json_path.relative_to(ROOT)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--openapi", action="store_true")
    parser.add_argument("--config-ref", action="store_true")
    parser.add_argument("--platforms", action="store_true")
    args = parser.parse_args()
    selected = args.openapi or args.config_ref or args.platforms
    if not selected:
        args.openapi = args.config_ref = args.platforms = True
    docs = ROOT / "docs"
    if args.config_ref:
        write_config_reference(docs / "configuration-reference.md")
        print("wrote docs/configuration-reference.md")
    if args.platforms:
        write_supported_platforms(docs / "supported-platforms.md")
        print("wrote docs/supported-platforms.md")
    if args.openapi:
        write_openapi(docs / "openapi.yaml")


if __name__ == "__main__":
    main()
